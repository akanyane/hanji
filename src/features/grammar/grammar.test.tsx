import { act, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it } from 'vitest'
import { GRAMMAR_LESSONS } from '../../content/grammar'
import { db } from '../../db/db'
import { getQuizSummary } from '../../db/quizAttempts'
import { settingsActions } from '../../stores/settings'
import { renderApp } from '../../test/renderApp'

beforeEach(async () => {
  await Promise.all(db.tables.map((t) => t.clear()))
})

describe('grammar home', () => {
  it('lists every lesson grouped by level', async () => {
    renderApp('/grammar')
    expect(
      await screen.findByRole('link', { name: /Partícula de tópico 은\/는/ }),
    ).toBeInTheDocument()
    expect(screen.getAllByText('Não iniciada')).toHaveLength(
      GRAMMAR_LESSONS.length,
    )
  })
})

describe('lesson page', () => {
  it('shows the explanation, formation, live conjugation table, examples and mistakes', async () => {
    renderApp('/grammar/present-polite')
    expect(
      await screen.findByRole('heading', { name: 'Presente educado (해요체)' }),
    ).toBeInTheDocument()
    expect(
      screen.getByRole('heading', { name: 'Como formar' }),
    ).toBeInTheDocument()
    // Generated by the conjugation engine, not written in the content.
    const table = screen.getByRole('heading', {
      name: 'Veja com verbos de verdade',
    }).parentElement
    expect(within(table as HTMLElement).getByText('몰라요')).toBeInTheDocument()
    expect(within(table as HTMLElement).getByText('더워요')).toBeInTheDocument()
    expect(
      screen.getByRole('heading', { name: 'Erros comuns' }),
    ).toBeInTheDocument()
  })

  it('runs the exercises and saves the score', async () => {
    const user = userEvent.setup()
    renderApp('/grammar/topic-eun-neun')
    await user.click(
      await screen.findByRole('button', { name: 'Fazer exercícios' }),
    )

    // Answer every question with the first choice.
    for (let i = 0; i < 3; i++) {
      await screen.findByText(new RegExp(`Questão ${i + 1} de 3`))
      await user.keyboard('1')
      await user.click(await screen.findByRole('button', { name: /Continuar/ }))
    }

    expect(await screen.findByText(/Você acertou \d de 3!/)).toBeInTheDocument()
    await waitFor(async () =>
      expect((await getQuizSummary('grammar:topic-eun-neun')).attempts).toBe(1),
    )
    expect(screen.getByRole('link', { name: /Próxima lição/ })).toHaveAttribute(
      'href',
      '/grammar/subject-i-ga',
    )
  })

  it('returns 404 for unknown lessons', async () => {
    renderApp('/grammar/nope')
    expect(
      await screen.findByText('Página não encontrada.'),
    ).toBeInTheDocument()
  })
})

describe('conjugator', () => {
  it('conjugates the verb in the URL and explains its irregularity', async () => {
    renderApp('/grammar/conjugator?verb=듣다')
    expect(
      await screen.findByText('Verbo · Irregular em ㄷ'),
    ).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '들어요' })).toBeInTheDocument()
    expect(
      screen.getByRole('button', { name: '들었습니다' }),
    ).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '들으면' })).toBeInTheDocument()
  })

  it('handles adjectives, special honorifics and invalid input', async () => {
    const user = userEvent.setup()
    renderApp('/grammar/conjugator?verb=덥다')
    expect(
      await screen.findByText('Adjetivo · Irregular em ㅂ'),
    ).toBeInTheDocument()
    expect(
      screen.getByText(/Adjetivos não têm progressivo/),
    ).toBeInTheDocument()

    await user.click(screen.getByRole('button', { name: '먹다' }))
    expect(
      await screen.findByText(/O honorífico usa outro verbo: 드시다/),
    ).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '드세요' })).toBeInTheDocument()

    const input = screen.getByLabelText(
      'Verbo ou adjetivo (forma de dicionário)',
    )
    await user.clear(input)
    await user.type(input, '먹어요')
    expect(await screen.findByRole('alert')).toHaveTextContent(
      'terminado em 다',
    )
  })

  it('lets ambiguous verbs be treated as regular', async () => {
    const user = userEvent.setup()
    renderApp('/grammar/conjugator?verb=걷다')
    expect(
      await screen.findByRole('button', { name: '걸어요' }),
    ).toBeInTheDocument()
    await user.click(screen.getByLabelText('Tratar como regular'))
    expect(
      await screen.findByRole('button', { name: '걷어요' }),
    ).toBeInTheDocument()
  })

  it('switches labels to English', async () => {
    act(() => settingsActions.setLocale('en'))
    renderApp('/grammar/conjugator?verb=하다')
    expect(await screen.findByText('Verb · 하다 verb')).toBeInTheDocument()
    expect(screen.getByText('Polite (해요체)')).toBeInTheDocument()
  })
})

describe('particle practice', () => {
  it('gives feedback with the reason and moves on', async () => {
    const user = userEvent.setup()
    renderApp('/grammar/particles')
    await screen.findByText(/Sequência: 0/)
    await user.keyboard('1')
    expect(
      await screen.findByText(/Correto!|A forma certa é/),
    ).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /Próxima/ }))
    await waitFor(() =>
      expect(
        screen.queryByText(/Correto!|A forma certa é/),
      ).not.toBeInTheDocument(),
    )
  })
})
